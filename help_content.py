def tip(key: str, extra: str = "") -> str:
    """버튼 힌트 창에 쓸 글(서식 있는 글). 이름 · 단축키 · 설명."""
    sec, name, keys, desc = ITEMS[key]
    head = f"<b>{html.escape(name)}</b>"
    if keys:
        head += f"&nbsp;&nbsp;<span style='color:#9fb4d9'>{html.escape(keys)}</span>"
    lines = [html.escape(desc)] if desc else []
    if extra:
        lines.append(extra)                 # extra는 이미 서식 있는 글
    return "<qt>" + head + ("<br>" + "<br>".join(lines) if lines else "") + "</qt>"


def section_rows(sec_key: str):
    return [(k, v[1], v[2], v[3]) for k, v in ITEMS.items() if v[0] == sec_key]


